"""Phase B12-A/B/C — counterfactual re-masking interventions on the global sampler (docs/counterfactual_global_denoising.md §2–5).

Model: the B11 best global student (base + lr1e-4 adapter + arm E adapter).  Sampler: non-monotonic confidence re-masking,
K = 16, S = 8 (engine/bdiff/global_sampler.py semantics, re-implemented here so that it can be RESUMED from an arbitrary
intermediate state).  For each dev prompt the answer is generated freely (control trajectory); for the blocks listed in
--blocks the state after step --at-step is taken as the intervention point and, from that SAME state with the SAME
remaining forwards of the block (S - at_step), the following are run to the end of the ANSWER (the remaining blocks are
generated by the unmodified sampler so that the final GSM8K answer exists):
  control         no intervention
  single          one visible position re-masked (every visible position of the state, up to --max-single)
  pair            two visible positions re-masked: all adjacent pairs + up to --pairs-nonadj random non-adjacent pairs
  multi           3 and 4 visible positions re-masked (random sets, --multi of each size)
  random          random sets of 1, 2, 3, 4 visible positions (comparison baseline, same counts as the policies above)
Intervention value = quality(intervention) - quality(control) with quality = (GSM8K correct, and dense auxiliaries:
adjacent duplicates in the intervened block, 4-gram repetition of the answer, whether the block changed, how many of its
tokens changed).  Oracle = per state the best candidate by final correctness (research upper bound; its search cost =
all candidate forwards, reported separately from the sampler's own cost).  Inference-feasible policies evaluated on the
same candidates: random (mean over random sets), lowest-confidence single / pair (confidence from the state's own
forward), confidence-ordered.  REF (the base model's greedy answer) is never used for selection; the GSM8K gold answer
is used only to score outcomes.
  CUDA_VISIBLE_DEVICES=4 PYTHONPATH=. .venv-train/bin/python bench/diag_counterfactual.py --model runs/zeta_sft_final_e5/final \
      --adapter runs/bdiff_e5_lr1e4/adapter --adapter2 runs/sa_E_remask_corr/adapter --n 50 --blocks 0,1,2 --at-step 4 \
      --out results/pure/b12_cf_E.json"""
import argparse, collections, json, os, random, sys, time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from distill.gpu_guard import check_env
check_env()
import torch
from transformers import AutoTokenizer, AutoModelForCausalLM
from bench.common import load_prompts, gpu_info, save_json, score
from engine.bdiff.model import BDiffModel
from engine.bdiff.corrupt import gamma


def rep4(toks):
    if len(toks) < 8:
        return 0.0
    g = [tuple(toks[i:i + 4]) for i in range(len(toks) - 3)]
    return 1.0 - len(set(g)) / len(g)


class Remask:
    """Non-monotonic confidence re-masking sampler that can be run step by step from any state."""

    def __init__(self, model, mask_id, K, S, schedule="linear"):
        self.model, self.mask_id, self.K, self.S, self.schedule = model, mask_id, K, S, schedule
        self.forwards = 0

    @torch.no_grad()
    def step(self, cache, P, x, s):
        """x: list[int] state before step s (1-based).  Returns (new state after step s incl. re-masking, conf of placed)."""
        K = len(x); dev = self.model.device
        xt = torch.tensor(x, device=dev)
        g = max(float((xt == self.mask_id).sum()) / K, 1e-3)
        lg = self.model.denoise(cache, P, xt[None], g).float(); self.forwards += 1
        lg[:, self.mask_id] = float("-inf")
        probs = torch.softmax(lg, -1); conf, pred = probs.max(-1)
        was_mask = xt == self.mask_id
        x_new = torch.where(was_mask, pred, xt)
        conf_all = torch.where(was_mask, conf, probs.gather(-1, xt.clamp_min(0)[:, None]).squeeze(-1))
        if s < self.S:
            n_mask = int(round(K * gamma(1.0 - s / self.S, self.schedule)))
            if n_mask > 0:
                low = conf_all.argsort()[:n_mask]
                x_new[low] = self.mask_id
        return x_new.tolist(), conf_all.tolist()

    def run(self, cache, P, x, s_from):
        """continue from state x (before step s_from) to the end of the block"""
        conf = None
        for s in range(s_from, self.S + 1):
            x, conf = self.step(cache, P, x, s)
        assert self.mask_id not in x
        return x, conf


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--adapter", default=None)
    ap.add_argument("--adapter2", default=None)
    ap.add_argument("--prompts", default="bench/prompts_gsm8k_dev.json")
    ap.add_argument("--n", type=int, default=50)
    ap.add_argument("--skip", type=int, default=0)
    ap.add_argument("--K", type=int, default=16)
    ap.add_argument("--steps", type=int, default=8)
    ap.add_argument("--blocks", default="0,1,2")
    ap.add_argument("--at-step", type=int, default=4)
    ap.add_argument("--max-single", type=int, default=8)
    ap.add_argument("--pairs-nonadj", type=int, default=4)
    ap.add_argument("--multi", type=int, default=2)
    ap.add_argument("--max-new-tokens", type=int, default=384)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    rng = random.Random(a.seed)
    dev = torch.device("cuda")
    tok = AutoTokenizer.from_pretrained(a.model)
    lm = AutoModelForCausalLM.from_pretrained(a.model, dtype=torch.bfloat16, attn_implementation="sdpa").to(dev).eval()
    mask_id = getattr(lm.config, "cdlm_mask_token_id", None) or tok.convert_tokens_to_ids("<|mask|>")
    from peft import PeftModel
    for ad in (a.adapter, a.adapter2):
        if ad:
            lm = PeftModel.from_pretrained(lm, ad).eval().merge_and_unload()
    model = BDiffModel(lm, mask_id, time_cond=False).to(dev).eval()
    K, S = a.K, a.steps
    sampler = Remask(model, mask_id, K, S)
    stop_ids = {tok.eos_token_id} | ({tok.convert_tokens_to_ids("<|im_end|>")} if "<|im_end|>" in tok.get_vocab() else set())
    prompts = load_prompts(a.prompts)[a.skip: a.skip + a.n]
    for p in prompts:
        ids = tok.apply_chat_template([{"role": "user", "content": p["prompt"]}], add_generation_prompt=True, enable_thinking=False, return_tensors="pt")
        p["ids"] = [int(t) for t in (ids[0] if torch.is_tensor(ids) else ids["input_ids"][0])]
    blocks_sel = [int(b) for b in a.blocks.split(",")]

    def finish_answer(ids, out, first_block_tokens):
        """given the generated prefix `out` and the finished intervened block, generate the rest of the answer normally"""
        out = list(out) + list(first_block_tokens)
        finish = None
        for q, t in enumerate(first_block_tokens):
            if t in stop_ids:
                out = list(out[: len(out) - len(first_block_tokens) + q + 1]); finish = "stop"; break
        while finish is None and len(out) < a.max_new_tokens:
            Kb = min(K, a.max_new_tokens - len(out)); P = len(ids) + len(out)
            cache = model.prefix_cache(torch.tensor([ids + out], device=dev)); sampler.forwards += 1
            x = [mask_id] * Kb
            x, _ = sampler.run(cache, P, x, 1)
            keep = Kb
            for q in range(Kb):
                if x[q] in stop_ids:
                    keep, finish = q + 1, "stop"; break
            out += x[:keep]
        return out

    t0 = time.time(); records = []; n_states = 0
    for p in prompts:
        ids = list(p["ids"]); out = []; finish = None; blk = 0
        while finish is None and len(out) < a.max_new_tokens:
            Kb = min(K, a.max_new_tokens - len(out)); P = len(ids) + len(out)
            cache = model.prefix_cache(torch.tensor([ids + out], device=dev)); sampler.forwards += 1
            x = [mask_id] * Kb
            # run to the intervention step and keep the state
            x_mid = None; conf_mid = None
            for s in range(1, S + 1):
                x, conf = sampler.step(cache, P, x, s)
                if s == a.at_step:
                    x_mid, conf_mid = list(x), list(conf)
            block_tokens = x
            if blk in blocks_sel and Kb == K and x_mid is not None:
                f_before = sampler.forwards
                vis = [q for q in range(K) if x_mid[q] != mask_id]
                n_states += 1
                # control: continue from x_mid (deterministic -> identical to the actual continuation) and finish the answer
                ctrl_block, _ = sampler.run(cache, P, list(x_mid), a.at_step + 1)
                ctrl_out = finish_answer(ids, out, ctrl_block); ctrl_text = tok.decode(ctrl_out, skip_special_tokens=True)
                ctrl = dict(correct=bool(score(p, ctrl_text)), rep4=rep4(ctrl_out), dup=sum(1 for q in range(1, K) if ctrl_block[q] == ctrl_block[q - 1]), block=ctrl_block)
                f_control = sampler.forwards - f_before
                cands = []
                singles = vis[: a.max_single]
                for q in singles:
                    cands.append(("single", (q,)))
                adj = [(vis[i], vis[i + 1]) for i in range(len(vis) - 1) if vis[i + 1] == vis[i] + 1]
                for pr in adj:
                    cands.append(("pair_adj", pr))
                nonadj = [(i, j) for i in vis for j in vis if j > i + 1]
                rng.shuffle(nonadj)
                for pr in nonadj[: a.pairs_nonadj]:
                    cands.append(("pair_nonadj", pr))
                for size in (3, 4):
                    if len(vis) >= size:
                        for _ in range(a.multi):
                            cands.append((f"multi{size}", tuple(sorted(rng.sample(vis, size)))))
                for size in (1, 2, 3, 4):
                    if len(vis) >= size:
                        cands.append((f"random{size}", tuple(sorted(rng.sample(vis, size)))))
                results = []
                f_search = 0
                for kind, pos in cands:
                    fb = sampler.forwards
                    x_int = list(x_mid)
                    for q in pos:
                        x_int[q] = mask_id
                    blk_int, _ = sampler.run(cache, P, x_int, a.at_step + 1)
                    out_int = finish_answer(ids, out, blk_int); text_int = tok.decode(out_int, skip_special_tokens=True)
                    f_search += sampler.forwards - fb
                    results.append(dict(kind=kind, pos=list(pos), conf_pos=[round(conf_mid[q], 3) for q in pos], correct=bool(score(p, text_int)), rep4=rep4(out_int),
                                        dup=sum(1 for q in range(1, K) if blk_int[q] == blk_int[q - 1]), block_changed=int(blk_int != ctrl_block),
                                        tokens_changed=sum(1 for q in range(K) if blk_int[q] != ctrl_block[q]), changed_at_pos=sum(1 for q in pos if blk_int[q] != ctrl_block[q])))
                records.append(dict(id=p["id"], blk=blk, step=a.at_step, n_visible=len(vis), conf_visible=[round(conf_mid[q], 3) for q in vis], control=ctrl, interventions=results,
                                    forwards_control=f_control, forwards_search=f_search))
                print(f"{p['id']} blk {blk}: control {ctrl['correct']} | best {max(r['correct'] for r in results)} | {len(results)} interventions, {f_search} search forwards, {time.time() - t0:.0f}s", flush=True)
            keep = Kb
            for q in range(Kb):
                if block_tokens[q] in stop_ids:
                    keep, finish = q + 1, "stop"; break
            out += block_tokens[:keep]; blk += 1
            if len(out) >= a.max_new_tokens:
                finish = finish or "length"
    # ---- analysis
    def agg(records):
        n = len(records); base = sum(r["control"]["correct"] for r in records)
        by_kind = collections.defaultdict(lambda: dict(n=0, w2c=0, c2w=0, same=0, block_changed=0, tok_changed=0, dup_delta=0.0, rep_delta=0.0))
        oracle = dict(any=0, single=0, pair=0, multi=0, harm_free_any=0); best_budget = collections.Counter()
        policy = collections.defaultdict(lambda: [0, 0, 0])   # name -> [n, w2c, c2w]
        for r in records:
            c = r["control"]["correct"]
            kinds_ok = collections.defaultdict(bool)
            for it in r["interventions"]:
                b = by_kind[it["kind"]]; b["n"] += 1
                b["w2c"] += int(not c and it["correct"]); b["c2w"] += int(c and not it["correct"]); b["same"] += int(c == it["correct"])
                b["block_changed"] += it["block_changed"]; b["tok_changed"] += it["tokens_changed"]; b["dup_delta"] += it["dup"] - r["control"]["dup"]; b["rep_delta"] += it["rep4"] - r["control"]["rep4"]
                if not c and it["correct"]:
                    kinds_ok[it["kind"].rstrip("0123456789").replace("_adj", "").replace("_nonadj", "")] = True
            if not c:
                oracle["any"] += int(any(kinds_ok.values())); oracle["single"] += int(kinds_ok["single"]); oracle["pair"] += int(kinds_ok["pair"]); oracle["multi"] += int(kinds_ok["multi"])
                if any(kinds_ok.values()):
                    best_budget[min(len(it["pos"]) for it in r["interventions"] if it["correct"])] += 1
            # inference-feasible policies: lowest-confidence single, lowest-confidence adjacent pair, random1
            singles = [it for it in r["interventions"] if it["kind"] == "single"]
            if singles:
                lc = min(singles, key=lambda it: it["conf_pos"][0]); pol = policy["lowest_conf_single"]; pol[0] += 1; pol[1] += int(not c and lc["correct"]); pol[2] += int(c and not lc["correct"])
            pairs = [it for it in r["interventions"] if it["kind"] == "pair_adj"]
            if pairs:
                lc = min(pairs, key=lambda it: sum(it["conf_pos"])); pol = policy["lowest_conf_pair"]; pol[0] += 1; pol[1] += int(not c and lc["correct"]); pol[2] += int(c and not lc["correct"])
            for k_ in ("random1", "random2", "random3", "random4"):
                rs = [it for it in r["interventions"] if it["kind"] == k_]
                if rs:
                    pol = policy[k_]; pol[0] += 1; pol[1] += int(not c and rs[0]["correct"]); pol[2] += int(c and not rs[0]["correct"])
        n_wrong = n - base
        return dict(states=n, control_correct=base, control_wrong=n_wrong,
                    by_kind={k: dict(n=v["n"], w2c_rate=round(v["w2c"] / max(1, v["n"]), 4), c2w_rate=round(v["c2w"] / max(1, v["n"]), 4), unchanged_outcome=round(v["same"] / max(1, v["n"]), 4),
                                     block_changed=round(v["block_changed"] / max(1, v["n"]), 4), tokens_changed=round(v["tok_changed"] / max(1, v["n"]), 3),
                                     dup_delta=round(v["dup_delta"] / max(1, v["n"]), 3), rep4_delta=round(v["rep_delta"] / max(1, v["n"]), 4)) for k, v in by_kind.items()},
                    oracle=dict(wrong_states_repairable_by_any=round(oracle["any"] / max(1, n_wrong), 4), by_single=round(oracle["single"] / max(1, n_wrong), 4), by_pair=round(oracle["pair"] / max(1, n_wrong), 4),
                                by_multi=round(oracle["multi"] / max(1, n_wrong), 4), smallest_repairing_set_size_hist=dict(sorted(best_budget.items())),
                                oracle_accuracy_if_applied_to_wrong_states_only=round((base + oracle["any"]) / max(1, n), 4)),
                    policies={k: dict(n=v[0], w2c_rate=round(v[1] / max(1, v[0]), 4), c2w_rate=round(v[2] / max(1, v[0]), 4), net=round((v[1] - v[2]) / max(1, v[0]), 4)) for k, v in policy.items()},
                    forwards=dict(control_per_state=round(sum(r["forwards_control"] for r in records) / max(1, n), 1), search_per_state=round(sum(r["forwards_search"] for r in records) / max(1, n), 1)))
    summary = agg(records)
    by_block = {str(b): agg([r for r in records if r["blk"] == b]) for b in blocks_sel if any(r["blk"] == b for r in records)}
    print("=== counterfactual", json.dumps({k: v for k, v in summary.items()}), flush=True)
    save_json(a.out, dict(model=a.model, adapter=a.adapter, adapter2=a.adapter2, n=len(prompts), blocks=blocks_sel, at_step=a.at_step, gpu=gpu_info(), seconds=round(time.time() - t0, 1),
                          total_forwards=sampler.forwards, summary=summary, by_block=by_block, records=records))


if __name__ == "__main__":
    main()
